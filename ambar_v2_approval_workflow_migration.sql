-- AMBAR Furniture V2: centralized approval queue foundation.
-- Run ONLY in the separate AMBAR V2 staging Supabase project after backup.
-- This migration creates storage only; server-side approval gates and UI must
-- be deployed before any operation is considered approval-protected.

create table if not exists public.ambar_approval_requests (
    id bigint generated by default as identity primary key,
    request_type text not null,
    status text not null default 'pending'
        check (status in ('pending', 'approved', 'rejected', 'cancelled', 'conflict')),
    requester_telegram_id text not null,
    requester_name text,
    request_summary text not null,
    request_payload jsonb not null default '{}'::jsonb,
    before_snapshot jsonb,
    base_updated_at timestamptz,
    approver_telegram_id text,
    approver_name text,
    decision_note text,
    created_at timestamptz not null default now(),
    decided_at timestamptz,
    applied_at timestamptz,
    result_reference text,
    idempotency_key text unique
);

create index if not exists ambar_approval_requests_status_created_idx
    on public.ambar_approval_requests (status, created_at desc);
create index if not exists ambar_approval_requests_requester_idx
    on public.ambar_approval_requests (requester_telegram_id, created_at desc);
create index if not exists ambar_approval_requests_type_idx
    on public.ambar_approval_requests (request_type, created_at desc);

alter table public.ambar_approval_requests enable row level security;

-- No direct browser access. Flask uses the server-side Supabase service key.
revoke all on table public.ambar_approval_requests from anon, authenticated;
grant select, insert, update, delete on table public.ambar_approval_requests to service_role;

grant usage, select on sequence public.ambar_approval_requests_id_seq to service_role;

comment on table public.ambar_approval_requests is
'AMBAR V2 approval queue. Pending requests must not alter official business records. Only server-verified Main Admin decisions may apply a request.';
